export function getProvinces(currentValue?: string): string[] {
  const list = Object.keys(PH_LOCATIONS)
  if (currentValue && !list.includes(currentValue)) {
    return [currentValue, ...list]
  }
  return list
}

export function getMunicipalities(province: string, currentValue?: string): string[] {
  if (!province) return currentValue ? [currentValue] : []
  const provinceMap = PH_LOCATIONS[province]
  const list = provinceMap ? Object.keys(provinceMap) : []
  if (currentValue && !list.includes(currentValue)) {
    return [currentValue, ...list]
  }
  return list
}

export function getBarangays(province: string, municipality: string, currentValue?: string): string[] {
  if (!province || !municipality) return currentValue ? [currentValue] : []
  const list = PH_LOCATIONS[province]?.[municipality] ?? []
  if (currentValue && !list.includes(currentValue)) {
    return [currentValue, ...list]
  }
  return list
}
